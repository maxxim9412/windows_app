/// Нормализация названия/сокращения книги: нижний регистр, ё→е,
/// без точек и пробелов. Напр. «1 Кор.» → «1кор».
String normalizeBookToken(String s) => s
    .toLowerCase()
    .replaceAll('ё', 'е')
    .replaceAll('.', '')
    .replaceAll(' ', '')
    .trim();

